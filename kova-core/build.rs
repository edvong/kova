use std::fs;
use std::path::PathBuf;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=src/dsl/function/aggregate/count.rs");
    println!("cargo:rerun-if-changed=src/dsl/function/scalar/length.rs");

    let base_dir = PathBuf::from("src/dsl/function");

    // Standard build file warning headers
    let autogen_header = "// @generated\n// This file is auto-generated by build.rs. DO NOT EDIT.\n\n";

    // ==========================================
    // Generate aggregate functions (based on Count)
    // ==========================================
    let aggr_dir = base_dir.join("aggregate");
    let count_code = fs::read_to_string(aggr_dir.join("count.rs"))
        .expect("Failed to read count.rs");

    let aggregates = vec!["Sum", "Avg", "Max", "Min"];
    for aggr in aggregates {
        let code = count_code.replace("Count", aggr);
        let final_code = format!("{}{}", autogen_header, code);

        let file_path = aggr_dir.join(format!("{}.rs", aggr.to_lowercase()));
        fs::write(&file_path, final_code).unwrap();
    }

    // ==========================================
    // Generate scalar functions (based on Length)
    // ==========================================
    let scalar_dir = base_dir.join("scalar");
    let length_code = fs::read_to_string(scalar_dir.join("length.rs"))
        .expect("Failed to read length.rs");

    let scalars = vec!["Lower", "Upper", "Abs"];
    for scalar in scalars {
        let code = length_code.replace("Length", scalar);
        let final_code = format!("{}{}", autogen_header, code);

        let file_path = scalar_dir.join(format!("{}.rs", scalar.to_lowercase()));
        fs::write(&file_path, final_code).unwrap();
    }
}