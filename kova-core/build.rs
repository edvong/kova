use std::fs;
use std::path::PathBuf;

struct FuncConfig {
    name: &'static str,
    target: &'static str,
    is_aggregate: bool,
    is_string: bool,
}

const FUNCTIONS: &[FuncConfig] = &[
    FuncConfig { name: "Sum", target: "T", is_aggregate: true, is_string: false },
    FuncConfig { name: "Max", target: "T", is_aggregate: true, is_string: false },
    FuncConfig { name: "Min", target: "T", is_aggregate: true, is_string: false },
    FuncConfig { name: "Avg", target: "T", is_aggregate: true, is_string: false },
    FuncConfig { name: "Count", target: "i64", is_aggregate: true, is_string: false },
    FuncConfig { name: "Length", target: "i64", is_aggregate: false, is_string: false },
    FuncConfig { name: "Abs", target: "T", is_aggregate: false, is_string: false },
    FuncConfig { name: "Lower", target: "String", is_aggregate: false, is_string: true },
    FuncConfig { name: "Upper", target: "String", is_aggregate: false, is_string: true },
];

fn main() {
    // Keep cargo from rebuilding unless these specific targets change.
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=src/dsl/function/template");

    generate_std_functions();
}

static NAME: &str = "{NAME}";
static TARGET: &str = "{TARGET}";

fn generate_std_functions() {
    let imports_tpl = include_str!("src/dsl/function/template/imports.rs.txt");
    let base_tpl = include_str!("src/dsl/function/template/base_impls.rs.txt");
    let agg_traits_tpl = include_str!("src/dsl/function/template/agg_traits.rs.txt");
    let scalar_traits_tpl = include_str!("src/dsl/function/template/scalar_traits.rs.txt");
    let common_tpl = include_str!("src/dsl/function/template/common_ops.rs.txt");
    let string_tpl = include_str!("src/dsl/function/template/string_ops.rs.txt");

    let mut generated_code = String::new();

    generated_code
        .push_str("// @generated\n// This file is auto-generated by build.rs. DO NOT EDIT.\n\n");
    generated_code.push_str(imports_tpl);
    generated_code.push_str("\n\n");

    for func in FUNCTIONS {
        generated_code
            .push_str(&base_tpl.replace(NAME, func.name).replace(TARGET, func.target));
        generated_code.push_str("\n\n");

        if func.is_aggregate {
            generated_code.push_str(&agg_traits_tpl.replace(NAME, func.name));
            generated_code.push_str("\n\n");
        } else {
            generated_code.push_str(&scalar_traits_tpl.replace(NAME, func.name));
            generated_code.push_str("\n\n");
        }

        generated_code
            .push_str(&common_tpl.replace(NAME, func.name).replace(TARGET, func.target));
        generated_code.push_str("\n\n");

        if func.is_string {
            generated_code.push_str(&string_tpl.replace(NAME, func.name));
            generated_code.push_str("\n\n");
        }
        
        if func.name == "Count" {
            generated_code.push_str(include_str!("src/dsl/function/template/count_star.rs.txt"));
            generated_code.push_str("\n\n");
        }
    }

    // Technically violates the standard "don't touch src in build.rs" convention,
    // but it's intentional.
    let dest_path = PathBuf::from("src/dsl/function/standard.rs");
    fs::write(&dest_path, generated_code).unwrap();
}