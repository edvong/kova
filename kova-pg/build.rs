fn gen_window() {
    // Grab the root directory of the current crate (kova-pg).
    let manifest_dir = env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR not set");
    let window_dir = PathBuf::from(manifest_dir).join("src/dsl/function/window");

    let lag_path = window_dir.join("lag.rs");
    let lead_path = window_dir.join("lead.rs");

    // Trick: Only re-trigger the build script if lag.rs is actually modified. Keeps compilation fast.
    println!("cargo:rerun-if-changed={}", lag_path.display());

    let lag_content = fs::read_to_string(&lag_path).expect("Failed to read lag.rs");

    // Dead-simple text replacement to morph Lag into Lead.
    let lead_content = lag_content.replace("Lag", "Lead").replace("lag", "lead");

    // Inject the auto-generated warning header at the top.
    let generated_content = format!(
        "// @generated\n// This file is auto-generated by build.rs. DO NOT EDIT.\n\n{}",
        lead_content
    );

    fs::write(&lead_path, generated_content).expect("Failed to write lead.rs");
}

fn gen_json() {
    let abs_path = Path::new("../kova-core/src/dsl/function/scalar/abs.rs");
    let row_to_json_path = Path::new("src/dsl/function/row_to_json.rs");

    println!("cargo:rerun-if-changed={}", abs_path.display());
    println!("cargo:rerun-if-changed={}", row_to_json_path.display());

    if !abs_path.exists() || !row_to_json_path.exists() {
        return;
    }

    let abs_content = fs::read_to_string(abs_path).expect("Failed to read abs.rs");
    let target_content = fs::read_to_string(row_to_json_path).expect("Failed to read row_to_json.rs");

    let clean_generic = |code: String| -> String {
        code.replace("DB: Database, ", "")
            .replace("DB, ", "Postgres, ")
            .replace("DB>", "Postgres>")
    };

    let proj_code = clean_generic(extract_block(
        &abs_content,
        "    // @SOURCE_COMMON_PROJECTION_START\n",
        "    // @SOURCE_COMMON_PROJECTION_END",
    ));
    let comp_code = clean_generic(extract_block(
        &abs_content,
        "    // @SOURCE_COMMON_COMPARATOR_START\n",
        "    // @SOURCE_COMMON_COMPARATOR_END",
    ));

    let mut new_content = replace_block(
        &target_content,
        "    // @GENERATED_COMMON_PROJECTION_START\n",
        "    // @GENERATED_COMMON_PROJECTION_END",
        &proj_code,
    );
    new_content = replace_block(
        &new_content,
        "    // @GENERATED_COMMON_COMPARATOR_START\n",
        "    // @GENERATED_COMMON_COMPARATOR_END",
        &comp_code,
    );

    if target_content != new_content {
        fs::write(row_to_json_path, new_content).expect("Failed to write row_to_json.rs");
    }
}

fn extract_block(content: &str, start_marker: &str, end_marker: &str) -> String {
    let start = content.find(start_marker)
        .unwrap_or_else(|| panic!("Missing start marker: {}", start_marker))
        + start_marker.len();
    let end = content.find(end_marker)
        .unwrap_or_else(|| panic!("Missing end marker: {}", end_marker));
    content[start..end].to_string()
}

fn replace_block(content: &str, start_marker: &str, end_marker: &str, new_block: &str) -> String {
    let start = content.find(start_marker)
        .unwrap_or_else(|| panic!("Missing start marker: {}", start_marker))
        + start_marker.len();
    let end = content.find(end_marker)
        .unwrap_or_else(|| panic!("Missing end marker: {}", end_marker));
    format!("{}{}{}", &content[..start], new_block, &content[end..])
}
