use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    // Grab the root directory of the current crate (kova-pg).
    let manifest_dir = env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR not set");
    let window_dir = PathBuf::from(manifest_dir).join("src/dsl/function/window");

    let lag_path = window_dir.join("lag.rs");
    let lead_path = window_dir.join("lead.rs");

    // Trick: Only re-trigger the build script if lag.rs is actually modified. Keeps compilation fast.
    println!("cargo:rerun-if-changed={}", lag_path.display());

    let lag_content = fs::read_to_string(&lag_path).expect("Failed to read lag.rs");

    // Dead-simple text replacement to morph Lag into Lead.
    let lead_content = lag_content.replace("Lag", "Lead").replace("lag", "lead");

    // Inject the auto-generated warning header at the top.
    let generated_content = format!(
        "// @generated\n// This file is auto-generated by build.rs. DO NOT EDIT.\n\n{}",
        lead_content
    );

    fs::write(&lead_path, generated_content).expect("Failed to write lead.rs");
}
