use std::fs;
use std::path::Path;

fn main() {
    // Mapping out the source files to their generated destination paths.
    let files = vec![
        ("src/dsl/function/json_extract.rs", "src/dsl/function/jsonb_extract.rs"),
        ("src/dsl/function/json_group_array.rs", "src/dsl/function/jsonb_group_array.rs"),
        ("src/dsl/function/json_object.rs", "src/dsl/function/jsonb_object.rs"),
    ];

    let header = "// @generated\n// This file is auto-generated by build.rs. DO NOT EDIT.\n\n";

    for (src_path, dst_path) in files {
        // Core trick: Explicitly tell Cargo to only rerun this build script if these specific
        // json_xxx.rs files are modified. Saves us unnecessary compilation time.
        println!("cargo:rerun-if-changed={}", src_path);

        let src = Path::new(src_path);
        let dst = Path::new(dst_path);

        if src.exists() {
            let content = fs::read_to_string(src).expect("Failed to read source file");

            // Performing a dead-simple text replacement strategy:
            // 1. "Json" -> "Jsonb" (Catches struct names like JsonExtract -> JsonbExtract, and enum variants like ExtFunction::JsonObject -> JsonbObject).
            // 2. "json_" -> "jsonb_" (Catches internal comments, snake_case macro/function names, etc.).
            let new_content = content.replace("Json", "Jsonb").replace("json_", "jsonb_");

            let final_content = format!("{}{}", header, new_content);

            fs::write(dst, final_content).expect("Failed to write generated file");
        }
    }
}
