#![allow(unreachable_code, dead_code, unused)]

use crate::Result;
use crate::models::comment::Comment;
use crate::models::order::Order;
use crate::models::post::Post;
use crate::models::user::User;
use kova::Options;
use kova::dsl::{Identifier, VirtualColumn};
use kova::dsl::func::{Count, JsonEach};
use kova::query::Select;
use kova::types::Engine;

// Marker types for compile-time static tagging
struct T1;
struct T2;
struct T3;
struct MixAlias;
struct CTEAlias;

/// Stress test for the TAG mechanism and Type-State Machine transitions in Self Joins.
fn compile_check_tags() -> Result<()> {
    let client = Options::in_memory().build()?;

    // ==========================================
    // Scenario 1: Basic Self Join
    // Validates:
    // 1. Select::tag() transition from `JustAddFrom` -> `Normal`
    // 2. Select::tag() transition from `JustAddJoin` -> `Normal`
    // 3. Column::tag() overriding the column's source table identifier
    // ==========================================
    let _ = client
        .select::<User>()
        .tag::<T1>()
        .inner_join::<User>(
            User::id.tag::<T1>().eq(User::id.tag::<T2>()),
        )
        .tag::<T2>()
        .columns((
            User::id.tag::<T1>(),
            User::name.tag::<T2>(),
        ))
        .filter(User::is_active.tag::<T1>().eq(true))
        .load_in::<(i32, String)>()?;

    // ==========================================
    // Scenario 2: Mixed Source Query (select_mix) Tagging
    // Validates: The `JustAddFrom` state generated by `select_mix` can be tagged
    // just like a standard `select`, seamlessly aliasing the implicitly CROSS JOINed dataset.
    // ==========================================
    let _ = client
        .select_mix::<User>(JsonEach(User::name))
        .tag::<MixAlias>() // Applies tag to the entirety of (User CROSS JOIN JsonEach)
        .columns((
            User::id.tag::<MixAlias>(),
            JsonEach::value.tag::<MixAlias>(),
        ))
        .load_in::<(i32, String)>()?;

    // ==========================================
    // Scenario 3: Identifier Tagging (Virtual Columns / CTEs)
    // Validates: Identifier::tag() generic support mapping.
    // ==========================================
    #[allow(non_upper_case_globals)]
    const virtual_col: VirtualColumn<Engine, f64> = kova::private::create_virtual_column("virtual_table", "score");

    let _ = client
        .select::<User>()
        .columns((
            User::id,
            virtual_col.tag::<CTEAlias>(),
        ))
        .filter(virtual_col.tag::<CTEAlias>().gt(50.0_f64))
        .load_in::<(i32, f64)>()?;

    // ==========================================
    // Scenario 4: Isolated Tagging Scope Inside Subqueries
    // Validates: Select::from().tag() state flow inside filter conditions.
    // ==========================================
    let _ = client
        .select::<Order>()
        .filter(
            Order::user_id.in_select(
                Select::from::<User>()
                    .tag::<T1>()
                    .columns(User::id.tag::<T1>())
                    .filter(User::is_active.tag::<T1>().eq(true)),
            ),
        )
        .load_as::<Order>()?;

    // ==========================================
    // Scenario 5: Deep Chained Joins with Multiple Tags
    // Validates: Cross-table tagging resolution inside complex grouped projections.
    // ==========================================
    let _ = client
        .select::<User>()
        .tag::<T1>()
        .left_join::<Post>(Post::author_id.tag::<T2>().eq(User::id.tag::<T1>()))
        .tag::<T2>()
        .right_join::<Comment>(Comment::post_id.tag::<T3>().eq(Post::id.tag::<T2>()))
        .tag::<T3>()
        .columns((
            User::name.tag::<T1>(),
            Post::title.tag::<T2>(),
            Count(Comment::id.tag::<T3>()).alias(User::id), // Tag applied inside an aggregate wrapper
        ))
        .group_by((User::name.tag::<T1>(), Post::title.tag::<T2>()))
        .load_in::<(String, String, i64)>()?;

    Ok(())
}